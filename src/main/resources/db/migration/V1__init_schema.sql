-- Epic IT POS v2.0 - initial schema (spec section 10)
-- All monetary columns are BIGINT: integer RWF math everywhere, no floats.
-- Timestamps are instants (stored UTC); report boundaries are computed in Africa/Kigali in code.

CREATE TABLE menu_item (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100) NOT NULL,
    price               BIGINT       NOT NULL CHECK (price > 0),
    stock               INT          NOT NULL CHECK (stock >= 0),
    low_stock_threshold INT          NOT NULL DEFAULT 5 CHECK (low_stock_threshold >= 0),
    color               VARCHAR(7)   NOT NULL,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE addon (
    id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name   VARCHAR(100) NOT NULL,
    active BOOLEAN      NOT NULL DEFAULT TRUE,
    price  BIGINT       NULL            -- reserved for future add-on pricing (A6)
);

-- "orders" because ORDER is a reserved word.
-- id is a surrogate key that is never exposed; order_number is the human-facing business number
-- (sequential per install, never reset, voids keep their number). The surrogate PK keeps a future
-- multi-tenant restaurant_id a one-column change.
CREATE TABLE orders (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number   INT         NOT NULL,
    status         VARCHAR(20) NOT NULL,
    payment_method VARCHAR(10) NOT NULL,
    total          BIGINT      NOT NULL DEFAULT 0,
    opened_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    finalized_at   TIMESTAMP WITH TIME ZONE NULL,
    voided_by      VARCHAR(20)  NULL,
    void_reason    VARCHAR(255) NULL,
    CONSTRAINT uq_orders_order_number UNIQUE (order_number)
);
CREATE INDEX idx_orders_status ON orders (status);
CREATE INDEX idx_orders_finalized_at ON orders (finalized_at);

-- item_name and unit_price are snapshots: menu edits must never rewrite history.
-- menu_item_id keeps its FK because menu items are only ever deactivated, never deleted.
CREATE TABLE order_line (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT       NOT NULL,
    menu_item_id BIGINT       NOT NULL,
    qty          INT          NOT NULL CHECK (qty > 0),
    item_name    VARCHAR(100) NOT NULL,
    unit_price   BIGINT       NOT NULL,
    CONSTRAINT fk_order_line_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT fk_order_line_menu_item FOREIGN KEY (menu_item_id) REFERENCES menu_item (id)
);
CREATE INDEX idx_order_line_order ON order_line (order_id);

CREATE TABLE order_line_addon (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_line_id BIGINT       NOT NULL,
    addon_id      BIGINT       NOT NULL,
    addon_name    VARCHAR(100) NOT NULL,
    note          VARCHAR(255) NULL,
    CONSTRAINT fk_ola_order_line FOREIGN KEY (order_line_id) REFERENCES order_line (id),
    CONSTRAINT fk_ola_addon FOREIGN KEY (addon_id) REFERENCES addon (id)
);
CREATE INDEX idx_ola_order_line ON order_line_addon (order_line_id);

-- Append-only. Covers owner actions only (cashiers are unauthenticated, spec section 5).
CREATE TABLE audit_log (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    actor      VARCHAR(20)  NOT NULL CHECK (actor = 'OWNER'),
    action     VARCHAR(40)  NOT NULL,
    entity     VARCHAR(60)  NULL,
    old_value  CLOB         NULL,
    new_value  CLOB         NULL,
    reason     VARCHAR(255) NULL
);
CREATE INDEX idx_audit_log_created_at ON audit_log (created_at);

-- Single row (id = 1). No schema_version (Flyway owns it) and no backup_path (lives in config.properties).
-- owner_pin_hash is NULL until the first-run wizard sets it.
CREATE TABLE settings (
    id                  INT PRIMARY KEY CHECK (id = 1),
    restaurant_name     VARCHAR(100) NOT NULL,
    owner_pin_hash      VARCHAR(100) NULL,
    low_stock_default   INT          NOT NULL DEFAULT 5,
    sound_muted         BOOLEAN      NOT NULL DEFAULT FALSE,
    failed_pin_attempts INT          NOT NULL DEFAULT 0,
    last_failed_pin_at  TIMESTAMP WITH TIME ZONE NULL,
    pin_locked_until    TIMESTAMP WITH TIME ZONE NULL
);
